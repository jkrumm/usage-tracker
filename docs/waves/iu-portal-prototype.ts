import { chromium } from "playwright-core";
import { mkdirSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
const key = (await Bun.stdin.text()).trim();
const base = "https://ue-self-service.app.iu-it.org";
const root = join(homedir(), ".local/share/iu-portal");
const out = join(root, "capture");
mkdirSync(out, { recursive: true });
const ctx = await chromium.launchPersistentContext(join(root, "profile"), { channel: "chrome", headless: true, viewport: { width: 1600, height: 1200 }, acceptDownloads: true });
const page = ctx.pages()[0] ?? (await ctx.newPage());
const frames: string[] = [];
page.on("websocket", (ws) => ws.on("framereceived", (f) => { const s = typeof f.payload === "string" ? f.payload : f.payload.toString("utf8"); frames.push(s.replace(/[\x00-\x08\x0b-\x1f]/g, " ")); }));
await page.goto(`${base}/cost-overview`, { waitUntil: "domcontentloaded" });
await page.waitForTimeout(4000);
await page.locator("input").first().fill(key);
await page.getByRole("button", { name: /load cost data/i }).click();
await page.waitForTimeout(6000);
for (const [range, gran] of [["1 Month", "Daily"], ["3 Months", "Monthly"]]) {
  await page.getByText(range, { exact: true }).click();
  await page.getByText(gran, { exact: true }).click();
  await page.getByRole("button", { name: /generate report/i }).click();
  await page.waitForTimeout(20000);
  const n = `cost-${range.replace(/ /g, "")}-${gran}`;
  writeFileSync(join(out, `${n}.html`), await page.content());
  writeFileSync(join(out, `${n}.txt`), await page.innerText("body"));
  await page.screenshot({ path: join(out, `${n}.png`), fullPage: true });
  const buttons = await page.getByRole("button").allInnerTexts();
  console.log(n, "buttons:", buttons.filter(Boolean).join(" | "));
}
writeFileSync(join(out, "cost-ws.log"), frames.join("\n---\n"));
await ctx.close();
